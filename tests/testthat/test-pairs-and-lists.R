test_that("pair selectors retain arbitrary values and use S3 dispatch", {
  payload <- list(values = c(1, 2), missing = NULL)
  p <- pair(payload, NULL)
  expect_s3_class(p, "pair")
  expect_true(is_pair(p))
  expect_false(is_pair(list(1, 2)))
  expect_identical(utils::head(p), payload)
  expect_null(utils::tail(p))
  expect_identical(utils::head(1:8), 1:6)
  expect_identical(utils::tail(1:8), 3:8)
})
test_that("mutations are shared by aliases including NULL replacements", {
  p <- pair(1, 2)
  alias <- p
  expect_invisible(set_head(p, c(3, 4)))
  expect_identical(utils::head(alias), c(3, 4))
  expect_invisible(set_tail(alias, NULL))
  expect_null(utils::tail(p))
  expect_invisible(set_head(alias, NULL))
  expect_null(utils::head(p))
  child <- pair("nested", "value")
  set_tail(p, child)
  set_head(child, "changed")
  expect_identical(utils::head(utils::tail(alias)), "changed")
})
test_that("List supports empty lists and retains element boundaries", {
  expect_null(List())
  expect_equal(len(NULL), 0)
  inner <- List("inside", "again")
  xs <- List(c(1, 2), NULL, inner)
  expect_equal(len(xs), 3)
  expect_identical(flatten_list(xs), list(c(1, 2), NULL, inner))
  expect_identical(flatten_list(NULL), list())
  expect_identical(flatten_list(List(NULL)), list(NULL))
  expect_error(flatten_list(pair(1, 2)))
})
test_that("flatten_pair traverses trees while flatten_list keeps elements", {
  inner <- List(2, List(3, 4))
  tree <- List(1, inner, 5)
  expect_identical(flatten_pair(tree), list(1, 2, 3, 4, 5))
  expect_identical(flatten_list(tree), list(1, inner, 5))
  expect_identical(flatten_pair(pair(1, 2)), list(1, 2))
  expect_identical(flatten_pair(List(c(1, 2), 3)), list(c(1, 2), 3))
  expect_identical(flatten_pair(NULL), list())
})
test_that("map and appnd return proper lists without changing inputs", {
  xs <- List(1, 2, 3)
  ys <- List(4, 5)
  mapped <- map(function(x) x * 10, xs)
  expect_identical(flatten_list(mapped), list(10, 20, 30))
  expect_identical(flatten_list(appnd(xs, ys)), list(1, 2, 3, 4, 5))
  expect_identical(flatten_list(xs), list(1, 2, 3))
  expect_identical(flatten_list(ys), list(4, 5))
  expect_null(map(identity, NULL))
  expect_identical(appnd(NULL, ys), ys)
  expect_identical(flatten_list(appnd(xs, NULL)), list(1, 2, 3))
})
test_that("do_call preserves vectors, NULL values, and an empty argument list", {
  inspect <- function(x, y, z) list(x = x, y = y, z = z)
  expect_identical(do_call(inspect, List(c(1, 2), NULL, "last")), list(x = c(1, 2), y = NULL, z = "last"))
  expect_identical(do_call(function() "zero arguments", NULL), "zero arguments")
  expect_equal(do_call("sum", List(1, 2, 3)), 6)
  expect_error(do_call(identity, 1))
  expect_error(do_call(identity, pair(1, 2)))
})
