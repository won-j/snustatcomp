test_that("gcd follows the lecture recurrence and handles zero", {
  expect_equal(gcd(206, 40), 2)
  expect_equal(gcd(54, 24), 6)
  expect_equal(gcd(54, -24), -6)
  expect_equal(gcd(0, 24), 24)
  expect_equal(gcd(24, 0), 24)
  expect_equal(gcd(0, 0), 0)
  expect_equal(gcd(17, 13), 1)
})
test_that("prime tests cover the boundary and composite squares", {
  expect_identical(vapply(c(-5, 0, 1), is_prime, logical(1)), c(FALSE, FALSE, FALSE))
  expect_identical(vapply(c(2, 3, 17, 43), is_prime, logical(1)), rep(TRUE, 4))
  expect_identical(vapply(c(4, 9, 25, 49, 221), is_prime, logical(1)), rep(FALSE, 5))
  expect_equal(smallest_divisor(49), 7)
  expect_equal(smallest_divisor(91), 7)
  expect_equal(smallest_divisor(43), 43)
  expect_equal(find_divisor(45, 3), 3)
  expect_equal(find_divisor(77, 4), 7)
  expect_true(divides(7, 91))
  expect_false(divides(4, 91))
  expect_true(divides(-3, 12))
  expect_true(divides(3, 0))
})
test_that("square keeps ordinary vectorized R arithmetic", {
  expect_equal(square(c(-3, 0, 2)), c(9, 0, 4))
  expect_equal(square(1 + 2i), -3 + 4i)
  expect_identical(square(numeric()), numeric())
})
