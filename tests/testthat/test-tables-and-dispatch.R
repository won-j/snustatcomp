test_that("assoc compares structural keys and distinguishes missing records", {
  key <- List("operation", List("type", "other"))
  record <- pair(key, "answer")
  records <- List(pair("unrelated", 0), record)
  expect_true(equal(key, List("operation", List("type", "other"))))
  expect_false(equal(key, List("operation", List("type", "different"))))
  expect_identical(assoc(List("operation", List("type", "other")), records), record)
  expect_identical(assoc("missing", records), FALSE)
  expect_identical(assoc("missing", NULL), FALSE)
})
test_that("two-key tables update records and keep independent state", {
  table <- make_table2()
  lookup <- table("lookup")
  insert <- table("insert!")
  other <- make_table2()
  expect_identical(lookup("operation", "number"), FALSE)
  expect_identical(insert("operation", "number", 10), "ok")
  expect_identical(insert("operation", "other", 20), "ok")
  expect_identical(insert("different", "number", 30), "ok")
  expect_identical(insert("operation", "number", 11), "ok")
  expect_identical(lookup("operation", "number"), 11)
  expect_identical(lookup("operation", "other"), 20)
  expect_identical(lookup("different", "number"), 30)
  expect_identical(lookup("missing", "number"), FALSE)
  expect_identical(lookup("operation", "missing"), FALSE)
  expect_identical(other("lookup")("operation", "number"), FALSE)
  insert(List("structural", "first"), List("structural", "second"), NULL)
  expect_null(lookup(List("structural", "first"), List("structural", "second")))
  insert(List("structural", "first"), List("structural", "second"), "updated")
  expect_identical(lookup(List("structural", "first"), List("structural", "second")), "updated")
})
test_that("reset refreshes the default table even through saved API functions", {
  with_empty_operation_table({
    saved_get <- Get
    saved_put <- Put
    independent <- make_table2()
    independent("insert!")("outside", "default", "preserved")
    expect_identical(Put("before", List("type"), "old"), "ok")
    expect_identical(saved_get("before", List("type")), "old")
    expect_invisible(reset_operation_table())
    expect_identical(Get("before", List("type")), FALSE)
    expect_identical(saved_get("before", List("type")), FALSE)
    saved_put("after", List("type"), "new")
    expect_identical(Get("after", List("type")), "new")
    expect_identical(independent("lookup")("outside", "default"), "preserved")
  })
})
test_that("tags retain their payload and reject untagged data", {
  payload <- List(c(1, 2), NULL)
  x <- attach_tag("example", payload)
  expect_identical(type_tag(x), "example")
  expect_identical(contents(x), payload)
  expect_null(contents(attach_tag("empty", NULL)))
  expect_error(type_tag(1))
  expect_error(contents(NULL))
})
test_that("generic dispatch selects registered type signatures", {
  with_empty_operation_table({
    x <- attach_tag("vector", c(1, 2))
    y <- attach_tag("empty", NULL)
    expect_error(apply_generic("inspect", List(x, y)), "no method")
    Put("inspect", List("vector", "empty"), function(a, b) list(a, b))
    expect_identical(apply_generic("inspect", List(x, y)), list(c(1, 2), NULL))
    expect_error(apply_generic("inspect", List(y, x)), "no method")
    Put("ready", NULL, function() "ready")
    expect_identical(apply_generic("ready", NULL), "ready")
  })
})
