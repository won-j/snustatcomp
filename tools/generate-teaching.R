#!/usr/bin/env Rscript
# Run from the package root (or pass --package=/absolute/package/path).
args <- commandArgs(trailingOnly = TRUE)
check <- "--check" %in% args
root_arg <- grep("^--package=", args, value = TRUE)
root <- if (length(root_arg)) sub("^--package=", "", root_arg[[1]]) else "."
root <- normalizePath(root, mustWork = TRUE)
if (!file.exists(file.path(root, "DESCRIPTION"))) stop("not a package root")
files <- c("numeric.R", "pair.R", "pair_helper.R", "assoc.R", "table2.R",
           "get_put.R", "tag.R", "complex_rect.R", "complex_polar.R",
           "apply_generic1.R", "complex_generic.R")
output_dir <- file.path(root, "inst", "teaching")
if (!check) dir.create(output_dir, recursive = TRUE, showWarnings = FALSE)
for (file in files) {
  original <- readLines(file.path(root, "R", file), warn = FALSE, encoding = "UTF-8")
  if (file == "get_put.R") {
    # This local-table lesson is an explicit template maintained in R/get_put.R.
    code <- sub("^# teaching> ?", "", grep("^# teaching>", original, value = TRUE))
  } else {
    # Roxygen prose and standalone documentation anchors are not lesson code.
    code <- original[!grepl("^#'", original) & !grepl("^NULL$", original)]
    first <- grep("^## ---- ", code)[1]
    if (is.na(first)) stop("missing teaching marker in ", file)
    code <- code[seq.int(first, length(code))]
  }
  if (!any(grepl("^## ---- ", code))) stop("no teaching chunks in ", file)
  generated <- c(paste0("# Generated from R/", file, "; do not edit this file."), code)
  target <- file.path(output_dir, file)
  if (check) {
    if (!file.exists(target) ||
        !identical(readLines(target, warn = FALSE, encoding = "UTF-8"), generated)) {
      stop("teaching source is stale: ", file, "; run tools/generate-teaching.R")
    }
  } else {
    writeLines(generated, target, useBytes = TRUE)
  }
}
message(if (check) "Teaching sources match their canonical R sources." else
        "Generated teaching sources from canonical R sources.")
